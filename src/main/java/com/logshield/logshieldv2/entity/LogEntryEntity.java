package com.logshield.logshieldv2.entity;

import jakarta.persistence.*;
import java.time.LocalDateTime;
import java.util.UUID;

/**
 * JPA Entity representing a log entry in the database.
 *
 * Separation from LogEntryResponse (DTO) is intentional:
 * - Entity: database representation — JPA annotations, DB concerns
 * - DTO: API representation — what client sends and receives
 *
 * The service layer converts between them — controller and client
 * never see JPA annotations or internal database fields.
 *
 * UUID primary key eliminates the timestamp collision problem
 * present in the previous ConcurrentHashMap implementation.
 * Two logs at the same second are now uniquely identified.
 */
@Entity
@Table(name = "log_entries")
public class LogEntryEntity {

    // UUID primary key — generated by DB on insert
    // Eliminates timestamp collision — each entry uniquely identified
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @Column(name = "id", updatable = false, nullable = false)
    private UUID id;

    // Timestamp as stored string — ISO format YYYY-MM-DD HH:MM:SS
    // Not unique — multiple entries can share a timestamp
    @Column(name = "timestamp", nullable = false)
    private String timestamp;

    // Log level — INFO, WARN, or ERROR
    @Column(name = "level", nullable = false, length = 10)
    private String level;

    // Log message — up to 500 characters as enforced by validation
    @Column(name = "message", nullable = false, length = 500)
    private String message;

    // Severity score — derived from level, stored for query efficiency
    // INFO=1, WARN=2, ERROR=3
    @Column(name = "severity_score", nullable = false)
    private int severityScore;

    // Audit field — when this record was created in the DB
    @Column(name = "created_at", updatable = false)
    private LocalDateTime createdAt;

    // JPA requires no-arg constructor
    public LogEntryEntity() {}

    // Constructor used by service layer when creating new entries
    public LogEntryEntity(String timestamp, String level,
                          String message, int severityScore) {
        this.timestamp     = timestamp;
        this.level         = level;
        this.message       = message;
        this.severityScore = severityScore;
        this.createdAt     = LocalDateTime.now();
    }

    // Getters
    public UUID      getId()            { return id; }
    public String    getTimestamp()     { return timestamp; }
    public String    getLevel()         { return level; }
    public String    getMessage()       { return message; }
    public int       getSeverityScore() { return severityScore; }
    public LocalDateTime getCreatedAt() { return createdAt; }

    // Setters — only for fields that can change
    public void setTimestamp(String timestamp)      { this.timestamp = timestamp; }
    public void setLevel(String level)              { this.level = level; }
    public void setMessage(String message)          { this.message = message; }
    public void setSeverityScore(int severityScore) { this.severityScore = severityScore; }
}